-- Drop the ten views first (they depend on the tables).
DROP VIEW IF EXISTS v10_user_feedback_summary;
DROP VIEW IF EXISTS v9_low_carbon_alternatives;
DROP VIEW IF EXISTS v8_favourite_saved_locations;
DROP VIEW IF EXISTS v7_condition_risk_by_route;
DROP VIEW IF EXISTS v6_ranked_route_recommendations;
DROP VIEW IF EXISTS v5_relevant_locations;
DROP VIEW IF EXISTS v4_users_and_feedback;
DROP VIEW IF EXISTS v3_faster_than_trip_average;
DROP VIEW IF EXISTS v2_faster_than_all_mode_averages;
DROP VIEW IF EXISTS v1_trip_route_details;

-- Drop tables in reverse dependency order.
DROP TABLE IF EXISTS feedback;
DROP TABLE IF EXISTS saved_location;
DROP TABLE IF EXISTS condition_observation;
DROP TABLE IF EXISTS route_segment;
DROP TABLE IF EXISTS route_option;
DROP TABLE IF EXISTS trip;
DROP TABLE IF EXISTS user_preference;
DROP TABLE IF EXISTS location;
DROP TABLE IF EXISTS app_user;

-- 1. Accounts and roles -------------------------------------------------
CREATE TABLE app_user (
    user_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(100) NOT NULL,
    email         VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    user_role     VARCHAR(20)  NOT NULL DEFAULT 'user'
                  CHECK (user_role IN ('admin', 'user', 'guest')),
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Reusable geographic locations -------------------------------------
CREATE TABLE location (
    location_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_name  VARCHAR(120) NOT NULL,
    street_address VARCHAR(180) NOT NULL,
    city           VARCHAR(80)  NOT NULL,
    latitude       NUMERIC(9,6) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude      NUMERIC(9,6) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    location_type  VARCHAR(20)  NOT NULL
                   CHECK (location_type IN ('home', 'work', 'school', 'public', 'other')),
    UNIQUE (latitude, longitude)
);

-- 3. One routing-preference profile per user ---------------------------
CREATE TABLE user_preference (
    preference_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           INTEGER NOT NULL UNIQUE REFERENCES app_user(user_id) ON DELETE CASCADE,
    preferred_mode    VARCHAR(20) NOT NULL
                      CHECK (preferred_mode IN ('driving', 'cycling', 'walking', 'transit')),
    max_walking_km    NUMERIC(4,1) NOT NULL DEFAULT 2.0 CHECK (max_walking_km >= 0),
    avoid_tolls       BOOLEAN NOT NULL DEFAULT FALSE,
    avoid_highways    BOOLEAN NOT NULL DEFAULT FALSE,
    prioritize_safety BOOLEAN NOT NULL DEFAULT TRUE
);

-- 4. Route-planning requests -------------------------------------------
CREATE TABLE trip (
    trip_id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 INTEGER NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    origin_location_id      INTEGER NOT NULL REFERENCES location(location_id),
    destination_location_id INTEGER NOT NULL REFERENCES location(location_id),
    requested_at            TIMESTAMP NOT NULL,
    departure_time          TIMESTAMP NOT NULL,
    trip_status             VARCHAR(20) NOT NULL
                            CHECK (trip_status IN ('planned', 'completed', 'cancelled')),
    actual_duration_min     INTEGER CHECK (actual_duration_min > 0),
    CHECK (origin_location_id <> destination_location_id)
);

-- 5. Alternative routes generated for a trip ---------------------------
CREATE TABLE route_option (
    route_id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id                INTEGER NOT NULL REFERENCES trip(trip_id) ON DELETE CASCADE,
    option_number          INTEGER NOT NULL CHECK (option_number > 0),
    travel_mode            VARCHAR(20) NOT NULL
                           CHECK (travel_mode IN ('driving', 'cycling', 'walking', 'transit')),
    distance_km            NUMERIC(7,2) NOT NULL CHECK (distance_km > 0),
    estimated_duration_min INTEGER NOT NULL CHECK (estimated_duration_min > 0),
    toll_cost              NUMERIC(7,2) NOT NULL DEFAULT 0 CHECK (toll_cost >= 0),
    is_selected            BOOLEAN NOT NULL DEFAULT FALSE,
    generated_at           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (trip_id, option_number)
);

-- At most one selected route per trip (partial unique index).
CREATE UNIQUE INDEX one_selected_route_per_trip
    ON route_option(trip_id)
    WHERE is_selected;

-- 6. Ordered road / transit sections of a route ------------------------
CREATE TABLE route_segment (
    segment_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id               INTEGER NOT NULL REFERENCES route_option(route_id) ON DELETE CASCADE,
    sequence_no            INTEGER NOT NULL CHECK (sequence_no > 0),
    start_location_id      INTEGER NOT NULL REFERENCES location(location_id),
    end_location_id        INTEGER NOT NULL REFERENCES location(location_id),
    road_name              VARCHAR(120) NOT NULL,
    distance_km            NUMERIC(7,2) NOT NULL CHECK (distance_km > 0),
    estimated_duration_min INTEGER NOT NULL CHECK (estimated_duration_min > 0),
    UNIQUE (route_id, sequence_no),
    CHECK (start_location_id <> end_location_id)
);

-- 7. Traffic, weather, closure and construction observations -----------
CREATE TABLE condition_observation (
    observation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    segment_id     INTEGER NOT NULL REFERENCES route_segment(segment_id) ON DELETE CASCADE,
    observed_at    TIMESTAMP NOT NULL,
    condition_type VARCHAR(20) NOT NULL
                   CHECK (condition_type IN ('traffic', 'weather', 'closure', 'construction')),
    severity       INTEGER NOT NULL CHECK (severity BETWEEN 0 AND 5),
    description    VARCHAR(200) NOT NULL,
    source_name    VARCHAR(80)  NOT NULL
);

-- 8. User labels and favourite places ----------------------------------
CREATE TABLE saved_location (
    saved_location_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           INTEGER NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    location_id       INTEGER NOT NULL REFERENCES location(location_id) ON DELETE CASCADE,
    label             VARCHAR(50) NOT NULL,
    is_favourite      BOOLEAN NOT NULL DEFAULT FALSE,
    saved_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, location_id)
);

-- 9. Ratings and comments about route results --------------------------
CREATE TABLE feedback (
    feedback_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      INTEGER NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    trip_id      INTEGER NOT NULL REFERENCES trip(trip_id) ON DELETE CASCADE,
    rating       INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comments     VARCHAR(500),
    submitted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, trip_id)
);

-- Supporting indexes for frequent foreign-key lookups (Phase III addition;
-- performance only, no change to the logical schema).
CREATE INDEX idx_trip_user            ON trip(user_id);
CREATE INDEX idx_route_option_trip    ON route_option(trip_id);
CREATE INDEX idx_route_segment_route  ON route_segment(route_id);
CREATE INDEX idx_observation_segment  ON condition_observation(segment_id);
CREATE INDEX idx_feedback_user        ON feedback(user_id);
